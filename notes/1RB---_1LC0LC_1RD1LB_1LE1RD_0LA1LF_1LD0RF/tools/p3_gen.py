#!/usr/bin/env python3
# p3_gen.py LINEFILE NMACRO K1 K2 [NAME] > P3Reach.v
# Writes the Rocq file that proves "the blank tape reaches the configuration of LINEFILE" with rocq/p3/P3Sim.v.
# LINEFILE: one round start as printed by chainb / p3_count (DUMP=): "steps state back run run ...".
# NMACRO: the number of macro steps p3_count reports for it (chain + single).
# The statement gives the first K1 runs, then a stretch of the 4-block band word (any number of copies, possibly
# none), then K2 more runs, then an unspecified rest.
import sys
M = "1RB---_1LC0LC_1RD1LB_1LE1RD_0LA1LF_1LD0RF"
BAND = ["010101", "110101", "011101", "010111"]
f = open(sys.argv[1]); toks = []
buf = f.read(1 << 22).split(' ')          # the head of the line is enough for K1
toks = buf[:-1]
nmacro, k1, k2 = int(sys.argv[2]), int(sys.argv[3]), int(sys.argv[4])
name = sys.argv[5] if len(sys.argv) > 5 else "reach"
val = lambda w: sum(int(c) << i for i, c in enumerate(w[:6]))
runs = [(val(t), int(t.split('^')[1]) if '^' in t else 1) for t in toks[3:]]
steps, st, back = toks[0], toks[1], val(toks[2])
if '^' in toks[2]: runs.insert(0, (back, int(toks[2].split('^')[1]) - 1))
sd = (ord(st) - 65) * 2
h1 = runs[:k1]; i = k1
band = [val(b) for b in BAND]
while [r for r in runs[i:i + 4]] == [(b, 1) for b in band]:
    i += 4
    if i + 4 > len(runs):                 # the band is longer than the part read: find its end in the full file
        allt = open(sys.argv[1]).read().split(); runs = [(val(t), int(t.split('^')[1]) if '^' in t else 1) for t in allt[3:]]
h2 = runs[i:i + k2]
lit = lambda h: "[" + "; ".join("(%d, %d)" % (b, n - 1) for b, n in h) + "]%uint63"
print(f"""(** Generated by tools/p3_gen.py: the blank tape reaches the round start at step {steps}
    ({nmacro} macro steps of P3Sim). *)
From BusyCoq Require Import Individual62.
From Coq Require Import ZArith List String.
From Coq Require Uint63 PArray.
From P3 Require Import P3Sim.
Import PrimInt63.
Definition tm := Eval compute in (TM_from_str "{M}"%string).
Definition tbl := Eval vm_compute in build_table tm.
Lemma tbl_ok : check_table tm tbl = true.
Proof. vm_cast_no_check (eq_refl true). Qed.

Definition NSTEPS : N := {nmacro}.
(** Runs as (block, copies - 1); bit i of a block is its i-th cell from the left. *)
Definition H1 : list (int * int) := {lit(h1)}.
Definition H2 : list (int * int) := {lit(h2)}.
Definition BAND : list Sym := (wr {band[0]} ++ wr {band[1]} ++ wr {band[2]} ++ wr {band[3]})%uint63.

Lemma final_shape :
  shape {k1} {band[0]} {band[1]} {band[2]} {band[3]} {k2} (run tbl NSTEPS init) = ({sd}, {back}, true, H1, H2)%uint63.
Proof. vm_cast_no_check (eq_refl ({sd}, {back}, true, H1, H2)%uint63). Time Qed.

Theorem {name} : exists n rest,
  c0 -[ tm ]->* const S0 <{{{{{st}}}}} (wr {back}%uint63 *> runs wr H1 (BAND^^n *> runs wr H2 rest)).
Proof.
  destruct (shape_ok _ _ _ _ _ _ _ _ _ _ _ {st} final_shape eq_refl) as (n & rest & Hd).
  exists n, rest. pose proof (run_ok tm tbl NSTEPS init tbl_ok) as H.
  rewrite init_ok, Hd in H. exact H.
Qed.
Print Assumptions {name}.""")
